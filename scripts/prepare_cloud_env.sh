#!/usr/bin/env bash
# publish-memory/*.env.local → YAML для gcloud run deploy --env-vars-file

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MEMORY="$ROOT/publish-memory"

read_env() {
  local file="$1"
  [[ -f "$file" ]] || return 0
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%%#*}"
    line="$(echo "$line" | xargs)"
    [[ -z "$line" || "$line" != *"="* ]] && continue
    local key="${line%%=*}"
    local val="${line#*=}"
    val="${val%\"}"; val="${val#\"}"
    val="${val%\'}"; val="${val#\'}"
    printf '%s: "%s"\n' "$key" "$val"
  done < "$file"
}

{
  echo "KARUSELKA_RUNTIME: cloud"
  echo "WORKER_STATE_BACKEND: dropbox"
  echo "ACCOUNTS_PAIRS_PATH: /app/config/accounts-pairs.json"
  echo "WORKER_STATE_DROPBOX_PATH: /Content_Plan/.karuselka/worker-state.json"
  echo "PUBLISH_MODE: grok_hook"
  echo "EXPECTED_IMAGE_SLIDES: \"6\""
  echo "CLOUD_RUN_RENDER_URL: https://ai-carousel-renderer-861393245289.europe-west1.run.app/generate-carousel"
  echo "RENDER_TIMEOUT_SEC: \"1200\""
  read_env "$MEMORY/airtable.env.local"
  read_env "$MEMORY/dropbox.env.local"
  read_env "$MEMORY/zernio.env.local"
  read_env "$MEMORY/max.env.local"
  read_env "$MEMORY/cloud-worker.env.local"
} > "$ROOT/deploy/cloud-worker/.env.deploy.yaml"

{
  echo "# generated by prepare_cloud_env.sh"
  [[ -f "$MEMORY/cloud-worker.env.local" ]] && grep -v '^#' "$MEMORY/cloud-worker.env.local" | grep '=' || true
} > "$ROOT/deploy/cloud-worker/.env.deploy"

echo "Wrote deploy/cloud-worker/.env.deploy.yaml"
